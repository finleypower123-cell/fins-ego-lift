// Generates Source/FelTables.h from the browser version's shared.js so both share one source of truth.
const fs = require('fs');
const dir = process.argv[2];
const src = fs.readFileSync(dir + '/engine.js', 'utf8') + '\n' + fs.readFileSync(dir + '/shared.js', 'utf8') +
  '\nmodule.exports={FinEngine,FEL_SECTIONS,FEL_PRESETS};';
const m = { exports: {} }; new Function('module', src)(m);
const { FinEngine, FEL_SECTIONS, FEL_PRESETS } = m.exports;
const D = FinEngine.defaults();
const q = (s) => JSON.stringify(s).replace(/\\u2019/g, "'");
const num = (v) => { const s = String(+v); return s.includes('.') || s.includes('e') ? s + 'f' : s + '.0f'; };
let o = '// GENERATED by tools/gen_tables.js from the browser version. Do not edit by hand.\n#pragma once\n#include "FelEngine.h"\n\nnamespace fel\n{\n';
o += 'struct KnobDef { const char* id; int section; const char* joke; const char* what; float min, max, def; bool logCurve; float step; const char* fmt; int egoType; float egoTarget, egoFloor; };\n';
o += 'struct SectionDef { const char* id; const char* onParam; const char* name; const char* what; const char* typeParam; const char* typeLabel; const char* typeOptions; bool bpm; int firstKnob, numKnobs; };\n';
o += 'struct PresetValue { const char* id; float value; };\n';
o += 'struct PresetDef { const char* name; const char* joke; float ego; const PresetValue* values; int numValues; };\n\n';
const knobs = []; const secs = [];
FEL_SECTIONS.forEach((s, si) => {
  secs.push(`    { ${q(s.id)}, ${q(s.on)}, ${q(s.name)}, ${q(s.what)}, ${s.type ? q(s.type.id) : 'nullptr'}, ${s.type ? q(s.type.label) : 'nullptr'}, ${s.type ? q(s.type.opts.join('|')) : 'nullptr'}, ${s.bpm ? 'true' : 'false'}, ${knobs.length}, ${s.knobs.length} }`);
  for (const k of s.knobs) {
    const et = !k.ego ? 0 : k.ego.t === 'amt' ? 1 : k.ego.t === 'width' ? 2 : 3;
    knobs.push(`    { ${q(k.id)}, ${si}, ${q(k.joke)}, ${q(k.what)}, ${num(k.min)}, ${num(k.max)}, ${num(D[k.id])}, ${k.curve === 'log'}, ${num(k.step || 0)}, ${q(k.fmt)}, ${et}, ${num(k.ego ? k.ego.e : 0)}, ${num(k.ego && k.ego.floor ? k.ego.floor : 0)} }`);
  }
});
o += `static const KnobDef KNOBS[] = {\n${knobs.join(',\n')}\n};\nstatic constexpr int NUM_KNOBS = ${knobs.length};\n\n`;
o += `static const SectionDef SECTIONS[] = {\n${secs.join(',\n')}\n};\nstatic constexpr int NUM_SECTIONS = ${secs.length};\n\n`;
FEL_PRESETS.forEach((p, i) => {
  const vals = Object.entries(p.p).map(([k, v]) => `{ ${q(k)}, ${num(v)} }`);
  o += `static const PresetValue PRESET_${i}[] = { ${vals.join(', ')} };\n`;
});
o += `\nstatic const PresetDef PRESETS[] = {\n${FEL_PRESETS.map((p, i) => `    { ${q(p.name)}, ${q(p.joke)}, ${num(p.ego)}, PRESET_${i}, ${Object.keys(p.p).length} }`).join(',\n')}\n};\nstatic constexpr int NUM_PRESETS = ${FEL_PRESETS.length};\n\n`;
const keys = Object.keys(D);
o += `struct ParamMember { const char* id; double Params::* ptr; };\nstatic const ParamMember PARAM_MEMBERS[] = {\n${keys.map((k) => `    { ${q(k)}, &Params::${k} }`).join(',\n')}\n};\nstatic constexpr int NUM_PARAM_MEMBERS = ${keys.length};\n\n`;
o += `inline double* paramPtr (Params& p, const char* id)\n{\n    for (const auto& m : PARAM_MEMBERS) { const char* a = m.id; const char* b = id; while (*a && *a == *b) { ++a; ++b; } if (*a == 0 && *b == 0) return &(p.*(m.ptr)); }\n    return nullptr;\n}\n} // namespace fel\n`;
fs.writeFileSync(process.argv[3], o);
console.log('knobs', knobs.length, 'sections', secs.length, 'presets', FEL_PRESETS.length, 'params', keys.length);
